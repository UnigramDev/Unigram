# Writes tw_ua_stylesheet.h from widget-sandbox's profile.json (tables.uaStylesheet), as twidget's CMakeLists.txt does:
# TwidgetCore bakes the profile's UA layer into its master CSS.
param([string]$ProfileJson, [string]$Out)
$css = (Get-Content -Raw -Encoding UTF8 $ProfileJson | ConvertFrom-Json).tables.uaStylesheet
if (-not $css) { throw "no tables.uaStylesheet in $ProfileJson" }
$text = "// Generated by Telegram.Native.Widgets.vcxproj from widget-sandbox's packages/core/profile.json (tables.uaStylesheet).`n" +
        "#pragma once`n" +
        "inline constexpr const char* TW_UA_STYLESHEET = R`"tw-ua($css)tw-ua`";`n"
New-Item -ItemType Directory -Force (Split-Path $Out) | Out-Null
[IO.File]::WriteAllText($Out, $text, (New-Object Text.UTF8Encoding $false))
