// Offline emitter for the benchmark's alternative field dispatch.
// Run: dotnet run GenAltParsers.cs
// Mirrors the type mapping in Telegram.Generators/SchemaGenerator.cs exactly, but dispatches
// on (name length -> SequenceEqual) instead of CRC32 -> switch(hash).

using System.Text;

var tl = @"C:\Source\Telegram\Libraries\tdjson\td_api.tl";
var outPath = @"C:\Source\Telegram\Telegram.Benchmarks\AltParsers.g.cs";

// (type name, whether nested types of the same family should use the Alt parsers too)
string[] wanted = ["localFile", "remoteFile", "message"];
string[] altNested = [];

var defs = new Dictionary<string, List<(string Name, string Type, bool IsVector, bool IsVectorOfVectors)>>();

var docs = new Dictionary<string, string>();

foreach (var raw in File.ReadAllLines(tl))
{
    var line = raw.Trim();

    // SchemaGenerator drops every "; for bots only" field, so the alternative must too or it
    // won't line up with the generated classes.
    if (line.StartsWith("//"))
    {
        foreach (var part in line.TrimStart('/').Split('@', StringSplitOptions.RemoveEmptyEntries))
        {
            var sp = part.Trim().Split(' ', 2);
            if (sp.Length == 2) docs[sp[0]] = sp[1];
        }
        continue;
    }

    if (line.Length == 0 || line.StartsWith("---")) { docs.Clear(); continue; }
    var eq = line.LastIndexOf(" = ");
    if (eq < 0 || !line.EndsWith(";")) { docs.Clear(); continue; }

    var head = line[..eq];
    var space = head.IndexOf(' ');
    var name = space < 0 ? head : head[..space];
    if (!wanted.Contains(name)) { docs.Clear(); continue; }

    var props = new List<(string, string, bool, bool)>();
    if (space > 0)
    {
        foreach (var arg in head[(space + 1)..].Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            var colon = arg.IndexOf(':');
            if (colon < 0) continue;
            var pn = arg[..colon];
            var pt = arg[(colon + 1)..];
            if (docs.TryGetValue(pn, out var d) && d.Contains("; for bots only")) continue;
            bool vec = false, vecvec = false;
            while (pt.StartsWith("vector<") && pt.EndsWith(">"))
            {
                vecvec = vec;
                vec = true;
                pt = pt[7..^1];
            }
            props.Add((pn, pt, vec, vecvec));
        }
    }
    defs[name] = props;
    docs.Clear();
}

foreach (var w in wanted)
{
    if (!defs.ContainsKey(w)) throw new Exception($"{w} not found in td_api.tl");
}

static string Camel(string name)
{
    var next = true;
    var sb = new StringBuilder();
    foreach (var c in name)
    {
        if (!char.IsLetterOrDigit(c)) { next = true; continue; }
        sb.Append(next ? char.ToUpper(c) : c);
        next = false;
    }
    return sb.ToString();
}

string Read((string Name, string Type, bool IsVector, bool IsVectorOfVectors) p)
{
    if (p.IsVector)
    {
        return p.Type switch
        {
            "Bool" => "reader.GetBooleanArray()",
            "int32" => "reader.GetInt32Array()",
            "int53" => "reader.GetInt64Array()",
            "int64" => "reader.GetInt64StringArray()",
            "double" => "reader.GetDoubleArray()",
            "string" => "reader.GetStringArray()",
            "bytes" => "reader.GetBase64StringArray()",
            _ => p.IsVectorOfVectors
                ? $"reader.GetObjectArrayArray(handler, FromJson_{Camel(p.Type)})"
                : $"reader.GetObjectArray(handler, FromJson_{Camel(p.Type)})"
        };
    }

    return p.Type switch
    {
        "Bool" => "reader.GetBoolean()",
        "int32" => "reader.GetInt32()",
        "int53" => "reader.GetInt64()",
        "int64" => "reader.GetInt64String()",
        "double" => "reader.GetDouble()",
        "string" => "reader.GetString()",
        "bytes" => "reader.GetBytesFromBase64()",
        _ => altNested.Contains(p.Type)
            ? $"FromJson_{Camel(p.Type)}_Alt(ref reader, handler)"
            : $"FromJson_{Camel(p.Type)}(ref reader, handler)"
    };
}

var b = new StringBuilder();
b.AppendLine("// <auto-generated />");
b.AppendLine("// Produced by scratchpad/GenAltParsers.cs from Libraries/tdjson/td_api.tl.");
b.AppendLine("// Candidate replacement for the CRC32 field dispatch in SchemaGenerator.WriteToJson:");
b.AppendLine("// switch on the property name's length, then compare it exactly. No hashing, and");
b.AppendLine("// no chance of an unknown field colliding with a known one.");
b.AppendLine("//");
b.AppendLine("// Partial of ClientJson so it can call the generated FromJson_* methods, which are private.");
b.AppendLine();
b.AppendLine("using System;"); // MemoryExtensions.SequenceEqual
b.AppendLine("using System.Text.Json;");
b.AppendLine("using Telegram.Td;");
b.AppendLine();
b.AppendLine("#nullable disable");
b.AppendLine();
b.AppendLine("namespace Telegram.Td.Api");
b.AppendLine("{");
b.AppendLine("    public partial class ClientJson");
b.AppendLine("    {");

foreach (var name in wanted)
{
    var className = Camel(name);
    var props = defs[name];

    b.AppendLine($"        internal static {className} FromJson_{className}_Alt(ref Utf8JsonReader reader, ClientResultHandler handler)");
    b.AppendLine("        {");
    b.AppendLine($"            var obj = new {className}();");
    b.AppendLine("            reader.ReadStartObject();");
    b.AppendLine();
    b.AppendLine("            while (reader.TokenType == JsonTokenType.PropertyName)");
    b.AppendLine("            {");
    b.AppendLine("                var name = reader.ValueSpan;");
    b.AppendLine("                reader.Read();");
    b.AppendLine();
    b.AppendLine("                switch (name.Length)");
    b.AppendLine("                {");

    foreach (var group in props.GroupBy(p => p.Name.Length).OrderBy(g => g.Key))
    {
        b.AppendLine($"                    case {group.Key}:");
        var first = true;
        foreach (var p in group)
        {
            var fieldName = Camel(p.Name);
            if (fieldName == className) fieldName += "Value";
            var el = first ? "if" : "else if";
            first = false;
            b.AppendLine($"                        {el} (name.SequenceEqual(\"{p.Name}\"u8)) obj.{fieldName} = {Read(p)};");
        }
        b.AppendLine("                        break;");
    }

    b.AppendLine("                }");
    b.AppendLine();
    b.AppendLine("                // Unlike ParseObject, this also skips an unknown *array* field. See README.");
    b.AppendLine("                if (reader.TokenType is JsonTokenType.StartObject or JsonTokenType.StartArray)");
    b.AppendLine("                {");
    b.AppendLine("                    reader.Skip();");
    b.AppendLine("                }");
    b.AppendLine();
    b.AppendLine("                reader.Read();");
    b.AppendLine("            }");
    b.AppendLine();
    b.AppendLine("            return obj;");
    b.AppendLine("        }");
    b.AppendLine();
}

b.AppendLine("    }");
b.AppendLine("}");

File.WriteAllText(outPath, b.ToString().ReplaceLineEndings("\r\n"), new UTF8Encoding(true));
Console.WriteLine($"wrote {outPath}");
foreach (var (k, v) in defs) Console.WriteLine($"  {k}: {v.Count} fields");
