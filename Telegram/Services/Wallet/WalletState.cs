using System.Collections.Generic;
using System.Numerics;
using Telegram.Td.Api;

namespace Telegram.Services.Wallet
{
    /// <summary>
    /// How far along one part of the wallet is. Each resource loads and fails on its own: history
    /// can fail while the state that carries the balance is fine, and the view has to say so.
    /// </summary>
    public enum WalletResourcePhase
    {
        Idle,
        Loading,
        Ready,
        Failed
    }

    /// <summary>
    /// The state of one resource, and why it failed if it did.
    /// </summary>
    public sealed class WalletResource
    {
        public static readonly WalletResource Idle = new WalletResource(WalletResourcePhase.Idle, null, false);
        public static readonly WalletResource Loading = new WalletResource(WalletResourcePhase.Loading, null, false);
        public static readonly WalletResource Ready = new WalletResource(WalletResourcePhase.Ready, null, false);

        public WalletResource(WalletResourcePhase phase, string message, bool canRetry)
        {
            Phase = phase;
            Message = message;
            CanRetry = canRetry;
        }

        public WalletResourcePhase Phase { get; }

        /// <summary>
        /// Diagnostic, not something to show a user as-is.
        /// </summary>
        public string Message { get; }

        public bool CanRetry { get; }

        public bool IsFailed => Phase == WalletResourcePhase.Failed;

        public bool IsLoading => Phase == WalletResourcePhase.Loading;
    }

    /// <summary>
    /// What the wallet looks like right now.
    /// </summary>
    /// <remarks>
    /// Immutable and replaced wholesale on every change.
    ///
    /// The identity and the balance come from TDLib's <c>tonWalletState</c>, which is pushed; the
    /// signing key is local and the engine holds it. <see cref="CanSign"/> is where those two meet:
    /// an account can have a wallet this device cannot spend from.
    ///
    /// This type exists because it is a composite of the two - which is also why history is not:
    /// a <see cref="TonWalletTransaction"/> is TDLib's from end to end, and a projection of it
    /// would be a copy of the same fields that has to be revisited every time TDLib adds one.
    ///
    /// Nothing generated by the engine appears here. The wallet views bind with <c>{Binding}</c>,
    /// which needs <c>[GeneratedBindableCustomProperty]</c> under AOT - an attribute that cannot be
    /// added to generated code.
    /// </remarks>
    public sealed class WalletState
    {
        private static readonly TonWalletTransaction[] NoActivity = new TonWalletTransaction[0];

        /// <summary>
        /// The account has no wallet. The starting state, and where deletion returns to.
        /// </summary>
        public static readonly WalletState None = new WalletState();

        private WalletState()
        {
            Currency = "USD";
            CurrencyRate = 1;
            Activity = NoActivity;
            ActivityResource = WalletResource.Idle;
        }

        public WalletState(
            string address,
            BigInteger balanceNanograms,
            bool synchronized,
            bool canSign,
            bool isBeingCreated,
            bool isBackupEnabled,
            bool canEnableBackup,
            bool canExportPhrase,
            string currency,
            double currencyRate,
            IReadOnlyList<TonWalletTransaction> activity,
            WalletResource activityResource,
            bool hasMoreActivity,
            int activityGeneration,
            TonWalletGaslessTransfersInfo gasless)
        {
            Address = address;
            BalanceNanograms = balanceNanograms;
            IsSynchronized = synchronized;
            CanSign = canSign;
            IsBeingCreated = isBeingCreated;
            IsBackupEnabled = isBackupEnabled;
            CanEnableBackup = canEnableBackup;
            CanExportPhrase = canExportPhrase;
            Currency = currency;
            CurrencyRate = currencyRate;
            Activity = activity ?? NoActivity;
            ActivityResource = activityResource ?? WalletResource.Idle;
            HasMoreActivity = hasMoreActivity;
            ActivityGeneration = activityGeneration;
            Gasless = gasless;
            HasWallet = address.Length > 0;
        }

        /// <summary>
        /// What is left of the daily allowance of transfers Telegram pays the gas for, or null
        /// before the account has said. Its quota changes on its own - every transfer spends one,
        /// and the day rolls over - so it arrives by update rather than being asked for.
        /// </summary>
        public TonWalletGaslessTransfersInfo Gasless { get; }

        /// <summary>
        /// Which history <see cref="Activity"/> belongs to. A new number means the one before it
        /// was abandoned rather than added to, and anything following it has to start again.
        /// </summary>
        /// <remarks>
        /// A history only grows at the top, so this changes rarely: another wallet, or a refresh
        /// that could not reach what it already held.
        /// </remarks>
        public int ActivityGeneration { get; }

        public bool HasWallet { get; }

        /// <summary>
        /// The wallet's address in its user-facing form, or null when there is no wallet.
        /// </summary>
        public string Address { get; }

        /// <summary>
        /// The balance in nanograms. Nanograms rather than grams because that is what the chain and
        /// the engine deal in, and <see cref="BigInteger"/> because the protocol permits values far
        /// beyond <see cref="long"/> - TDLib's own gram fields are int53, which caps at about nine
        /// million TON.
        /// </summary>
        public BigInteger BalanceNanograms { get; }

        /// <summary>
        /// Whether the balance is known yet. False is not zero and must not be shown as zero.
        /// </summary>
        public bool IsSynchronized { get; }

        /// <summary>
        /// Whether this device holds the signing key. Without it the wallet can be watched but not
        /// spent from, and the way back is the recovery phrase.
        /// </summary>
        public bool CanSign { get; }

        /// <summary>
        /// The server is still creating the wallet. There is no address to show yet.
        /// </summary>
        public bool IsBeingCreated { get; }

        /// <summary>
        /// The recovery phrase is in the Telegram cloud, behind the account password.
        /// </summary>
        public bool IsBackupEnabled { get; }

        public bool CanEnableBackup { get; }

        /// <summary>
        /// The phrase can be read back with <c>getTonWalletSecretPhrase</c>.
        /// </summary>
        public bool CanExportPhrase { get; }

        /// <summary>
        /// The currency the user asked amounts to be shown in, beside the grams.
        /// </summary>
        public string Currency { get; }

        /// <summary>
        /// How many units of <see cref="Currency"/> one dollar buys, which is the direction TDLib
        /// quotes it in - about 3.67 for AED. One for USD itself, and <b>zero while the rates have
        /// not arrived</b>: a converted amount cannot be shown yet, and anything shown in its place
        /// would be dollars wearing the wrong name.
        /// </summary>
        public double CurrencyRate { get; }

        /// <summary>
        /// History as TDLib reports it, newest first, older pages appended as they load. Never null.
        /// </summary>
        /// <remarks>
        /// Only TDLib can say which Telegram user is on the other side of a transfer, so this is
        /// its <c>getTonWalletTransactions</c> and not anything read off the chain.
        /// </remarks>
        public IReadOnlyList<TonWalletTransaction> Activity { get; }

        public WalletResource ActivityResource { get; }

        /// <summary>
        /// Whether an older page exists. Loading it is <c>LoadMoreActivityAsync</c>.
        /// </summary>
        public bool HasMoreActivity { get; }
    }

    /// <summary>
    /// The result of a send: TDLib broadcast the message the engine signed.
    /// </summary>
    /// <summary>
    /// Why a recovery phrase did not bind. Each of these is something to tell the user, and which
    /// words to tell them is the view's to decide.
    /// </summary>
    public enum WalletBindFailure
    {
        /// <summary>
        /// The account has no wallet. Nothing here can make one: the server creates them.
        /// </summary>
        NoWallet,

        /// <summary>
        /// The words are not a recovery phrase - mistyped, out of order, or from somewhere else
        /// entirely.
        /// </summary>
        InvalidPhrase,

        /// <summary>
        /// A valid phrase, for a different wallet. Refused rather than kept: it would sign
        /// messages the account's wallet cannot accept, and the mistake would surface much later.
        /// </summary>
        OtherWallet
    }

    /// <summary>
    /// What binding a phrase came to: the state it left the wallet in, or why it changed nothing.
    /// </summary>
    public sealed class WalletBindResult
    {
        public WalletBindResult(WalletState state)
        {
            State = state;
        }

        public WalletBindResult(WalletBindFailure failure)
        {
            Failure = failure;
        }

        public WalletState State { get; }

        public WalletBindFailure? Failure { get; }
    }

    public sealed class WalletTransferResult
    {
        public WalletTransferResult(string messageHash, bool isGasless, TonWalletTransaction transaction)
        {
            MessageHash = messageHash;
            IsGasless = isGasless;
            Transaction = transaction;
        }

        public WalletTransferResult(Error error)
        {
            Error = error;
        }

        /// <summary>
        /// Why the server refused the transfer, or null when it did not. The same shape every other
        /// request in the app answers with, so the caller decides what to say about it.
        /// </summary>
        public Error Error { get; }

        /// <summary>
        /// The hash the transaction can be found by once it lands, with
        /// <c>getTonWalletTransactionByMsgHash</c>.
        /// </summary>
        public string MessageHash { get; }

        /// <summary>
        /// The transfer as it settled, or null if it had not by the time the account answered.
        /// </summary>
        /// <remarks>
        /// The server holds the request open while it waits for the transfer to be included -
        /// around twenty seconds, thirty for a gasless one - so in the ordinary case the finished
        /// transaction comes back with the reply and there is nothing to poll for. Null is a
        /// normal outcome and not a failure: it means the wait ran out, and
        /// <see cref="MessageHash"/> is how to ask again.
        /// </remarks>
        public TonWalletTransaction Transaction { get; }

        /// <summary>
        /// Whether a relayer paid the gas, which is decided by the server and not by the caller.
        /// </summary>
        public bool IsGasless { get; }

    }
}
